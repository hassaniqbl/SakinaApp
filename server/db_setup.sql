SC_DELIVERY -> SC_SIX_WEEK_POSTNATAL_CHECKUP (1-to-many)
SC_DELIVERY -> SC_ANNUAL_POSTNATAL_CHECKUP (1-to-many)
Soft delete:

All tables include IS_DELETED BIT DEFAULT 0.
Recommended practice: never DELETE rows; instead UPDATE IS_DELETED=1.
*/

