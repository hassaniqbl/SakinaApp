-- 15.2 Join check (patient -> anemia checkups -> performa)
SELECT
p.PATIENT_ID,
p.PATIENT_NAME,
a.ANEMIA_CHECKUP_ID,
ap.ANEMIA_PERFORMA_ID
FROM SC_PATIENT p
JOIN SC_ANEMIA_CHECKUP a
ON a.PATIENT_ID = p.PATIENT_ID
JOIN SC_ANEMIA_PERFORMA ap
ON ap.ANEMIA_CHECKUP_ID = a.ANEMIA_CHECKUP_ID
WHERE p.IS_DELETED = b'0'
AND a.IS_DELETED = b'0'
AND ap.IS_DELETED = b'0'
ORDER BY p.PATIENT_ID DESC, a.ANEMIA_CHECKUP_ID DESC;

