CREATE DATABASE IF NOT EXISTS SAKINACARE;

USE SAKINACARE;

CREATE TABLE IF NOT EXISTS users (
  id INT NOT NULL AUTO_INCREMENT,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS PATIENT_PROFILE (
  PATIENT_REGISTRATION_NUMBER VARCHAR(100) PRIMARY KEY,
  REGISTRATION_DATE DATETIME,
  PATIENT_NAME VARCHAR(255),
  CNIC_NUMBER VARCHAR(50),
  PHONE_NUMBER VARCHAR(50),
  RELIGION VARCHAR(100),
  PATIENT_PROFESSION VARCHAR(255),
  PATIENT_MONTHLY_SALARY VARCHAR(100),
  AGE VARCHAR(50),
  ADDRESS TEXT,
  LOCATION VARCHAR(255),
  ESTIMATED_DATE_OF_DELIVERY DATETIME,
  BASELINE_HAEMOGLOBIN_COUNT VARCHAR(100),
  EDUCATION VARCHAR(100),
  RESIDENCE_CONDITION VARCHAR(100),
  RESIDENCE_OWNERSHIP VARCHAR(100),
  HUSBAND_NAME VARCHAR(255),
  GRAVIDA INT,
  PARA INT,
  MISCARRIAGE INT,
  ANTENATAL_VISITS INT,
  CREATED_BY_LATITUDE DECIMAL(10,7),
  CREATED_BY_LONGITUDE DECIMAL(10,7),
  CREATED_AT DATETIME,
  UPDATED_AT DATETIME,
  CREATED_BY VARCHAR(255),
  UPDATED_BY VARCHAR(255)
);



